"""Generate `src/_help_bundle.py`: the in-app help, inside the executable.

    python scripts/build_help_bundle.py [--out PATH]
    python scripts/build_help_bundle.py --page-out dist/docs/help.html

`build.ps1` runs this before compiling the GUI and deletes the result afterwards (also when the
compile fails). The module holds plain literals (schema, digest, payload) for the markdown and the
same three for the compiled HTML page, and runs no code on import. The formats and the reasons for
them are in `helpers/help_docs.py` and `helpers/markdown_html.py`; this file only reads the
documents that module names, so there is still exactly one list of them.

`--page-out` writes the SAME page as a standalone file, with `{{placeholders}}` filled by neutral
descriptions (it has no machine to ask). `build.ps1` ships it as `docs\\help.html`.

Exits non-zero and writes nothing if any help document is missing, empty or not UTF-8, or if a link
into the help points at nothing: a bundle built from fewer documents would be a smaller Help,
silently, and a page that dropped a link would be a worse one.
"""

import argparse
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from constants import APP_VERSION  # noqa: E402
from helpers import help_docs  # noqa: E402

DEFAULT_OUT = ROOT / "src" / "_help_bundle.py"

_TEMPLATE = '''# Generated by scripts/build_help_bundle.py -- do not edit, do not commit.
SCHEMA = {schema}
DIGEST = "{digest}"
PAYLOAD = "{payload}"
PAGES_SCHEMA = {pages_schema}
PAGES_DIGEST = "{pages_digest}"
PAGES_PAYLOAD = "{pages_payload}"
'''


def compile_page(documents: dict):
    """The compiled page for `documents`; raises `help_docs.BundleError` on a dead link."""
    return help_docs.compile_page(documents, APP_VERSION)


def render() -> str:
    """The module text for the documents currently on disk."""
    documents = help_docs.source_documents()
    schema, digest, payload = help_docs.encode_bundle(documents)
    page = compile_page(documents)
    pages_schema, pages_digest, pages_payload = help_docs.encode_pages({help_docs.PAGE_NAME: page.html})
    return _TEMPLATE.format(schema=schema, digest=digest, payload=payload, pages_schema=pages_schema,
                            pages_digest=pages_digest, pages_payload=pages_payload)


def static_page() -> str:
    """The standalone copy: the same compiled page, placeholders filled with neutral values."""
    page = compile_page(help_docs.source_documents())
    return help_docs.fill_page(page.html, help_docs.static_values(APP_VERSION))


def write_atomically(path: Path, text: str) -> None:
    """Temp file beside the target, then replace: an interrupted run leaves no half module."""
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def main(argv: "list[str] | None" = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--page-out", type=Path, default=None,
                        help="write only the standalone help page here, not the bundle module")
    args = parser.parse_args(argv)
    try:
        if args.page_out is not None:
            text = static_page()
            write_atomically(args.page_out, text)
            print("build_help_bundle: wrote %s (%d bytes)" % (args.page_out, len(text)))
            return 0
        text = render()
    except help_docs.BundleError as exc:
        print("build_help_bundle: %s" % exc, file=sys.stderr)
        return 1
    write_atomically(args.out, text)
    print("build_help_bundle: wrote %s (%d bytes)" % (args.out, len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
