"""tests/test_lessons_delivery.py — the shared gotchas reach every project.

The baseline's index said "read `docs/gotchas/x.md`" while nothing ever put those
files in a project (measured on Fortuna Lab: a `project-baseline.md`, no gotchas).
Everything here pins a way that delivery could go wrong WITHOUT anything raising:
a lesson silently missing, a hand edit overwritten, a copy attributed to the wrong
source, a delivered file left public in a repository that keeps its instructions
private, or one bad file stopping the other fifteen.
"""
