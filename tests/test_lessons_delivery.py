TEMPLATES = os.path.join(REPO_ROOT, "templates")

GIT = shutil.which("git") or ""
needs_git = pytest.mark.skipif(not GIT, reason="git not installed")

BASELINE_TEXT = "# Project Baseline Rules\n\n## Tokensave: Use It First\n"


def _corpus(**overrides):
    """A tiny in-memory corpus: real specs, invented text, optional overrides."""
    return tuple(ld.Lesson(spec, overrides.get(spec.source_rel,
                                               "# %s\n\nbody\n" % spec.source_rel))
                 for spec in ld.LESSONS)


def _dest(root, rel):
    return os.path.join(str(root), *rel.split("/"))


# ── the inventory is explicit, and matches what actually ships ────────────

def test_the_inventory_names_every_template_lesson_and_nothing_else():
    """A new file in templates/gotchas/ must be a decision, not a side effect."""
    on_disk = {"gotchas/" + n for n in os.listdir(os.path.join(TEMPLATES, "gotchas"))
               if n.endswith(".md")} | {"NUITKA_GOTCHAS.md"}
    assert {s.source_rel for s in ld.LESSONS} == on_disk


def test_every_source_exists_and_is_non_empty():
    corpus = ld.load_corpus(TEMPLATES)
    assert all(lesson.text for lesson in corpus), \
        [l.spec.source_rel for l in corpus if not l.text]


def test_destinations_are_unique_fixed_and_inside_docs_gotchas():
    dests = ld.dest_rels()
    assert len(set(dests)) == len(dests)
    assert all(d.startswith(ld.GOTCHA_DIR + "/") and ".." not in d
               and not os.path.isabs(d) and "\\" not in d for d in dests)
    assert len({s.source_rel for s in ld.LESSONS}) == len(ld.LESSONS)


def test_every_path_the_baseline_index_names_is_delivered_and_vice_versa():
    """The link the whole feature exists for: what the index says to read must
    be a file a project actually receives."""
    text = open(os.path.join(TEMPLATES, "project-baseline.md"),
                encoding="utf-8").read()
    named = set(re.findall(r"`(docs/gotchas/[^`]+\.md)`", text))
    assert named == set(ld.dest_rels()), (
        "index names but not delivered: %s; delivered but not indexed: %s"
        % (sorted(named - set(ld.dest_rels())),
           sorted(set(ld.dest_rels()) - named)))
    assert "`gotchas/" not in text, "an index path still points at the old layout"


# ── managed copies: identity is the source, not only the hash ─────────────

def test_the_header_records_the_source_and_reads_it_back():
    text = mc.render_copy("body\n", "gotchas/a.md")
    facts = mc.parse_copy(text, "gotchas/a.md")
    assert facts.header == mc.HEADER_OK and facts.source_id == "gotchas/a.md"


def test_identical_bodies_from_different_sources_are_not_interchangeable(tmp_path):
    """Two lessons may share a body; a hash alone could not tell them apart."""
    body = "same body\n"
    path = tmp_path / "docs" / "gotchas" / "a.md"
    path.parent.mkdir(parents=True)
    path.write_text(mc.render_copy(body, "gotchas/b.md"), encoding="utf-8")

    result = mc.write_managed(
        str(tmp_path), mc.ManagedCopySpec("docs/gotchas/a.md", "gotchas/a.md", body))

    assert result.ok is False and result.state_before == mc.COPY_INVALID
    assert "b.md" in path.read_text(encoding="utf-8"), "was overwritten"


def test_a_baseline_header_written_before_this_change_is_still_current():
    """Every project in the fleet carries the old spelling; it must not go
    stale merely because the grammar became general."""
    legacy = ("<!-- tokensave-manager:copy project-baseline.md sha256=%s "
              "- generated by TokenSave Manager; edit the template there, not "
              "this file -->\n%s" % (mc.content_sha(BASELINE_TEXT), BASELINE_TEXT))
    facts = bc.parse_copy(legacy)
    assert bc.classify_copy(facts, bc.content_sha(BASELINE_TEXT)) == bc.COPY_CURRENT


def test_a_header_naming_another_source_is_invalid_for_the_baseline_too():
    other = mc.render_copy(BASELINE_TEXT, "gotchas/x.md")
    assert bc.parse_copy(other).header == bc.HEADER_INVALID


# ── delivery: per artifact, never a transaction ───────────────────────────

def test_a_fresh_project_receives_every_lesson_and_reads_back_current(tmp_path):
    corpus = _corpus()
    outcomes = ld.sync_lessons(str(tmp_path), corpus)

    assert {o.outcome for o in outcomes} == {ld.OUT_WRITTEN}
    assert len(outcomes) == len(ld.LESSONS)
    assert {f.state for f in ld.read_lessons(str(tmp_path), corpus)} == \
        {mc.COPY_CURRENT}


def test_a_second_run_changes_nothing(tmp_path):
    corpus = _corpus()
    ld.sync_lessons(str(tmp_path), corpus)
    before = {r: open(_dest(tmp_path, r), "rb").read() for r in ld.dest_rels()}
    again = ld.sync_lessons(str(tmp_path), corpus)
    assert {o.outcome for o in again} == {ld.OUT_CURRENT}
    assert ld.written_files(again) == ()
    assert {r: open(_dest(tmp_path, r), "rb").read()
            for r in ld.dest_rels()} == before


def test_an_outdated_lesson_is_refreshed(tmp_path):
    target = ld.LESSONS[0]
    ld.sync_lessons(str(tmp_path), _corpus())
    newer = _corpus(**{target.source_rel: "# newer\n"})
    outcomes = {o.dest_rel: o for o in ld.sync_lessons(str(tmp_path), newer)}
    assert outcomes[target.dest_rel].outcome == ld.OUT_WRITTEN
    assert outcomes[target.dest_rel].state_before == mc.COPY_OUTDATED
    assert "# newer" in open(_dest(tmp_path, target.dest_rel),
                             encoding="utf-8").read()


def test_the_fleet_case_unchanged_edited_and_missing_are_each_handled(tmp_path):
    """A is current, B has a hand edit, C lacks one. Each is its own result."""
    corpus = _corpus()
    a, b, c = (tmp_path / n for n in "abc")
    for root in (a, b, c):
        ld.sync_lessons(str(root), corpus)

    edited_rel, missing_rel = ld.dest_rels()[1], ld.dest_rels()[2]
    edited = _dest(b, edited_rel)
    with open(edited, "a", encoding="utf-8") as fh:
        fh.write("\nMY OWN NOTE\n")
    edited_bytes = open(edited, "rb").read()
    os.remove(_dest(c, missing_rel))

    out_a = ld.sync_lessons(str(a), corpus)
    out_b = {o.dest_rel: o for o in ld.sync_lessons(str(b), corpus)}
    out_c = {o.dest_rel: o for o in ld.sync_lessons(str(c), corpus)}

    assert {o.outcome for o in out_a} == {ld.OUT_CURRENT}
    assert out_b[edited_rel].outcome == ld.OUT_REFUSED
    assert out_b[edited_rel].state_before == mc.COPY_EDITED
    assert open(edited, "rb").read() == edited_bytes, "a hand edit was overwritten"
    assert sum(o.outcome == ld.OUT_CURRENT for o in out_b.values()) == \
        len(ld.LESSONS) - 1, "one refusal must not stop the others"
    assert out_c[missing_rel].outcome == ld.OUT_WRITTEN
    assert os.path.isfile(_dest(c, missing_rel))


def test_one_unreadable_destination_does_not_stop_the_rest(tmp_path):
    """A directory where a lesson should be: unreadable, and not ours to touch."""
    blocked = ld.dest_rels()[0]
    os.makedirs(_dest(tmp_path, blocked))
    outcomes = {o.dest_rel: o for o in ld.sync_lessons(str(tmp_path), _corpus())}

    assert outcomes[blocked].outcome == ld.OUT_REFUSED
    assert outcomes[blocked].state_before == mc.COPY_UNREADABLE
    assert sum(o.outcome == ld.OUT_WRITTEN for o in outcomes.values()) == \
        len(ld.LESSONS) - 1
    assert "1 refused" in ld.outcomes_text(outcomes.values())


def test_an_unreadable_source_is_reported_per_artifact_not_dropped(tmp_path):
    lost = ld.LESSONS[3]
    outcomes = {o.dest_rel: o for o in ld.sync_lessons(
        str(tmp_path), _corpus(**{lost.source_rel: ""}))}
    assert outcomes[lost.dest_rel].outcome == ld.OUT_FAILED
    assert "could not be read" in outcomes[lost.dest_rel].reason
    assert not os.path.exists(_dest(tmp_path, lost.dest_rel))
    facts = {f.dest_rel: f for f in ld.read_lessons(
        str(tmp_path), _corpus(**{lost.source_rel: ""}))}
    assert facts[lost.dest_rel].state == ld.STATE_SOURCE_UNREADABLE


