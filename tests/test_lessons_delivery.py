def _posture(root, reach=ip.REACH_RESOLVED, copy=bc.COPY_CURRENT):
    return types.SimpleNamespace(display_root=str(root), reach=reach,
                                 copy_state=copy)


def test_only_a_project_with_a_current_resolving_baseline_receives_lessons(tmp_path):
    corpus = _corpus()
    assert iw.deliver_lessons(_posture(tmp_path, reach=ip.REACH_ORPHANED), corpus) == ()
    assert iw.deliver_lessons(_posture(tmp_path, copy=bc.COPY_OUTDATED), corpus) == ()
    assert iw.deliver_lessons(_posture(tmp_path), None) == ()
    assert not os.path.exists(os.path.join(str(tmp_path), "docs"))
    assert len(iw.deliver_lessons(_posture(tmp_path), corpus)) == len(ld.LESSONS)


def test_an_outcome_reports_lessons_as_their_own_dimension():
    outcomes = (ld.LessonOutcome("docs/gotchas/a.md", ld.OUT_WRITTEN),
                ld.LessonOutcome("docs/gotchas/b.md", ld.OUT_REFUSED, "edited",
                                 "docs/gotchas/b.md is edited - not overwritten"))
    result = iw.ApplyOutcome(iw.OUTCOME_ALREADY_RESOLVED, lessons=outcomes)
    text = result.render()
    assert "instructions: already resolved" in text
    assert "lessons: 1 written, 1 refused" in text
    assert result.lesson_files == ("docs/gotchas/a.md",)
    assert result.mutated and result.wrote is False
    # No corpus given: exactly the sentence it always was.
    assert iw.ApplyOutcome(iw.OUTCOME_WIRED).render() == "wired"


# -- the wiring path, against a real project on disk -------------------------

@pytest.fixture
def templates(tmp_path):
    d = tmp_path / "templates"
    d.mkdir()
    (d / "project-baseline.md").write_text(BASELINE_TEXT, encoding="utf-8")
    return d


def _project(tmp_path, templates, name="proj"):
    root = tmp_path / name
    root.mkdir()
    (root / "CLAUDE.md").write_text("@BASIC_INSTRUCTIONS.md\n", encoding="utf-8")
    (root / "BASIC_INSTRUCTIONS.md").write_text(bc.LOCAL_INCLUDE_LINE + "\n",
                                                encoding="utf-8")
    (root / "project-baseline.md").write_bytes(
        bc.render_copy(BASELINE_TEXT).encode("utf-8"))
    return root


def _posture_of(root, templates):
    return ip.read_project(
        str(root), root.name, str(templates),
        ip.canonical(str(templates / "project-baseline.md")), BASELINE_TEXT, "", {})


def _apply(root, templates, lessons, git_exe=""):
    return iw.apply_to_project(
        _posture_of(root, templates),
        ip.canonical(str(templates / "project-baseline.md")), str(templates),
        "", False, BASELINE_TEXT, claude_projects={}, git_exe=git_exe,
        lessons=lessons)


def test_an_already_wired_project_receives_the_lessons_through_the_normal_apply(
        tmp_path, templates):
    root = _project(tmp_path, templates)
    result = _apply(root, templates, _corpus())
    assert result.outcome == iw.OUTCOME_ALREADY_RESOLVED
    assert {o.outcome for o in result.lessons} == {ld.OUT_WRITTEN}
    assert result.mutated
    for rel in ld.dest_rels():
        assert os.path.isfile(_dest(root, rel))


def test_the_delivered_path_resolves_from_the_project_root(tmp_path, templates):
    """The link, not merely file presence: every path the baseline index names
    must open from the project root after delivery."""
    root = _project(tmp_path, templates)
    _apply(root, templates, ld.load_corpus(TEMPLATES))
    index = open(os.path.join(TEMPLATES, "project-baseline.md"),
                 encoding="utf-8").read()
    for rel in set(re.findall(r"`(docs/gotchas/[^`]+\.md)`", index)):
        path = _dest(root, rel)
        assert os.path.isfile(path), rel
        assert open(path, encoding="utf-8").readline().startswith(
            "<!-- tokensave-manager:copy ")


def test_an_excluded_project_gets_neither_the_baseline_nor_the_lessons(
        tmp_path, templates, monkeypatch):
    """A skipped project must never hold a baseline whose index points at files
    that were withheld."""
    import dataclasses
    root = _project(tmp_path, templates)
    posture = dataclasses.replace(_posture_of(root, templates), excluded=True,
                                  exclude_reason="vendor clone")
    monkeypatch.setattr(ip, "read_project",
                        lambda *a, **k: posture)
    result = iw.apply_to_project(
        posture, ip.canonical(str(templates / "project-baseline.md")),
        str(templates), "", False, BASELINE_TEXT, claude_projects={},
        lessons=_corpus())
    assert result.outcome == iw.OUTCOME_SKIPPED_BLOCKED
    assert result.lessons == ()
    assert not os.path.exists(os.path.join(str(root), "docs"))


# ── git alignment: the third level of the chain ───────────────────────────

COPY = bc.COPY_BASENAME
GOTCHA = ld.dest_rels()[0]


def _pair(rel, referrer=COPY):
    return ia.CompanionPair(rel, referrer, ia.KIND_GOTCHA)


def _facts(ref_git, comp_git, comp_fs=ia.FS_EXISTS, repo=ia.REPO):
    return ia.Facts(repo, {COPY: ia.PathFact(ia.FS_EXISTS, ref_git),
                           GOTCHA: ia.PathFact(comp_fs, comp_git)})


@pytest.mark.parametrize("ref,comp,pending", [
    (ia.LOCAL, ia.LOCAL, False),      # already aligned
    (ia.LOCAL, ia.OPEN, True),        # the KicomAI bug, one level down
    (ia.OPEN, ia.OPEN, False),
    (ia.TRACKED, ia.OPEN, False),     # both will be committed together
    (ia.TRACKED, ia.TRACKED, False),
])
def test_gotcha_alignment_table(ref, comp, pending):
    result = ia.decide([_pair(GOTCHA)], _facts(ref, comp))
    assert bool(result.pending) is pending
    assert not result.unknown


def test_a_visible_referrer_with_an_ignored_lesson_is_only_a_note():
    result = ia.decide([_pair(GOTCHA)], _facts(ia.TRACKED, ia.LOCAL))
    assert result.pending == () and result.notes


def test_a_tracked_lesson_under_a_local_referrer_is_reported_never_untracked():
    result = ia.decide([_pair(GOTCHA)], _facts(ia.LOCAL, ia.TRACKED))
    assert result.pending == ()
    assert "git rm --cached" in result.notes[0]


@pytest.mark.parametrize("ref,comp", [(ia.UNKNOWN, ia.OPEN), (ia.LOCAL, ia.UNKNOWN)])
def test_unknown_is_never_acted_on_for_lessons(ref, comp):
    result = ia.decide([_pair(GOTCHA)], _facts(ref, comp))
    assert result.pending == () and result.unknown


def _chain(root, files):
    return types.SimpleNamespace(
        display_root=str(root),
        chain=tuple(canonical(os.path.join(str(root), f)) for f in files),
        baseline_directives=(("BASIC_INSTRUCTIONS.md", 1, COPY),))


def test_lessons_are_companions_of_the_baseline_copy_and_only_when_present(tmp_path):
    posture = _chain(tmp_path, ["CLAUDE.md", "BASIC_INSTRUCTIONS.md", COPY])
    assert not [p for p in ia.companions_of(posture)
                if p.kind == ia.KIND_GOTCHA]
    ld.sync_lessons(str(tmp_path), _corpus())
    pairs = [p for p in ia.companions_of(posture) if p.kind == ia.KIND_GOTCHA]
    assert {p.companion_rel for p in pairs} == set(ld.dest_rels())
    assert {p.referrer_rel for p in pairs} == {COPY}


def test_without_the_baseline_copy_in_the_chain_nothing_refers_to_the_lessons(
        tmp_path):
    ld.sync_lessons(str(tmp_path), _corpus())
    posture = _chain(tmp_path, ["CLAUDE.md"])
    assert not [p for p in ia.companions_of(posture)
                if p.kind == ia.KIND_GOTCHA]


def _run(root, *args):
    return subprocess.run([GIT, "-C", str(root)] + list(args), check=True,
                          capture_output=True, text=True)


def _local_only_repo(root, ignore="CLAUDE.md\nBASIC_INSTRUCTIONS.md\n"):
    _run(root, "init", "-q")
    _run(root, "config", "user.email", "t@example.com")
    _run(root, "config", "user.name", "t")
    (root / ".gitignore").write_text(ignore, encoding="utf-8")
    _run(root, "add", ".gitignore")
    _run(root, "commit", "-q", "-m", "init")


@needs_git
def test_a_local_only_project_ignores_the_lessons_through_all_three_levels(
        tmp_path, templates):
    """KicomAI's shape. CLAUDE.md and BASIC are ignored; the baseline copy and
    every lesson must end up ignored too, in ONE apply, or the next commit
    publishes files whose referrer is private."""
    root = _project(tmp_path, templates)
    _local_only_repo(root)

    result = _apply(root, templates, _corpus(), git_exe=GIT)

    porcelain = _run(root, "status", "--porcelain", "--untracked-files=all").stdout
    assert porcelain.strip() == "M .gitignore", porcelain
    assert result.alignment.unconfirmed == ()
    confirmed = {p.companion_rel for p in result.alignment.confirmed}
    assert set(ld.dest_rels()) <= confirmed
    assert COPY in confirmed


@needs_git
def test_a_tracked_referrer_leaves_the_lessons_open_and_writes_no_gitignore_rule(
        tmp_path, templates):
    root = _project(tmp_path, templates)
    _local_only_repo(root, ignore="# nothing local\n")
    result = _apply(root, templates, _corpus(), git_exe=GIT)
    assert result.alignment is None or result.alignment.confirmed == ()
    assert "docs/gotchas" not in (root / ".gitignore").read_text(encoding="utf-8")


