"""The post-read advisory hook: render it, install it, know whether it is there.

WHAT THIS IS. A ``PostToolUse`` hook on ``Read``. After an eligible whole-file
read in a project carrying tokensave metadata, the next model turn receives one
line saying ``tokensave_read`` can serve indexed content for that file. It is a
**post-read advisory, not an interception**: the model had already chosen its
tool before any hook ran, so the target is the *next* decision.

WHY IT EXISTS. Measured 2026-09-11 across the 8 transcripts touched since the
baseline's tokensave rule was strengthened: 319 ``Read`` against 21
``tokensave_read``, and all 21 of those in this repository. Fortuna Lab called
``tokensave_context`` 13 times, ``tokensave_status`` 6 and ``tokensave_search``
2 -- and ``tokensave_read`` zero times. The graph was in active use; only the
body read was unrouted. The difference is enforcement: tokensave's own
``PreToolUse`` hook matches ``Agent|Grep|Bash|Glob`` and has no file-body
branch, so the half of the rule that is enforced is the half that lands.

THREE RULES THIS MODULE KEEPS, each with its reason.

1. **The emitted object never carries a permission key.** Not ``deny``, and not
   ``allow`` either: ``allow`` skips the permission prompt, so a hook that "only
   ever allows" silently auto-approves every read it sees. Advisory means the
   output is ``additionalContext`` and nothing else. ``test_read_nudge`` asserts
   this across the whole input space it can reach, because it is the invariant
   keeping this feature from becoming a permissions change nobody asked for.

2. **``.tokensave/`` presence is a proxy, and the naming says so.** It
   establishes ``project_with_tokensave_metadata``, never ``is_indexed`` --
   freshness, ignore rules, parser coverage and exclusions all sit between the
   two facts. So the advisory says tokensave *can serve indexed content for* the
   file, which is what was checked, rather than promising the file comes back.
   This is the Roadmap-11 mistake -- a file-content verdict rendered as
   effective scope -- refusing to happen again somewhere new.

3. **Path identity is lexical, deliberately.** It matches
   ``instructions_posture.canonical``, so a path reached through a junction
   reads the same way here and in the Manager. Resolving links in the hook while
   the Manager does not would produce "Manager says indexed, nudge says not"
   with nothing to point at.

ONE SOURCE OF TRUTH FOR THE PREDICATE. ``HOOK_SCRIPT`` is a standalone script
AND an importable module: its predicate sits at module level and ``main()`` runs
only under ``__main__``. ``predicate_module()`` imports the rendered text, so
the adherence measurement in ``scripts/measure_tokensave_adherence.py`` runs the
*identical* predicate rather than a second implementation of it. A denominator
computed by a near-copy is the number most worth getting wrong quietly.

It is a string constant rather than a file read from disk for the same reason
``scaffold._AUTO_COMMIT_HELPER`` is: the Manager ships as a Nuitka build, where
``inspect.getsource`` and reading a sibling ``.py`` both fail.
"""

