# `hashlib` and `tempfile` are imported lazily, inside the two functions that
# need them. Measured on this machine: a bare interpreter starts in 30.8 ms,
# `json`+`os`+`sys` costs 43.9, `hashlib` adds 6.5 and `tempfile` a further
# 14.3 -- and only an ELIGIBLE read ever reaches the state directory. Deferring
# them takes the common path (every sliced read, every image, every file
# outside an indexed project) from ~62 ms to ~44 ms, and that path runs far
# more often than the nudge does.

#: Serialised-response floor. Chosen from a measurement, not a feeling: over
#: 692 allowlisted whole-file reads (two weeks, 2026-09-11) the distribution was
#: p25 2,458 B, p50 6,453 B, p90 20,783 B. 2,048 B sits just under p25 and
#: excludes 20.2% of them -- roughly 500 tokens, below which the reminder costs
#: the same order as what it could save.
MIN_RESPONSE_BYTES = 2048
MAX_MARKERS = 500
MAX_ANCESTORS = 24
ENV_DISABLE = "TOKENSAVE_DISABLE_READ_NUDGE"
STATE_ROOT = "tokensave-read-nudge"
CAPPED_SENTINEL = ".capped"

ADVICE = ("This file is in a project with a tokensave index; tokensave_read "
          '(mode "lines" / "map") can serve indexed content for it.')

# Verdicts. Everything that is not ELIGIBLE is a reason rather than a bare
# False, so the measurement can report WHERE the denominator went instead of
# only how big it ended up.
NOT_READ = "not_read"
NO_PATH = "no_path"
SLICED = "sliced"
EXCLUDED_EXTENSION = "excluded_extension"
SMALL = "small"
NO_METADATA_PROJECT = "no_metadata_project"
ELIGIBLE = "eligible"
DISABLED = "disabled"
ALREADY_NUDGED = "already_nudged"

#: An allowlist, not a "looks like text" test: there is no budget to read a file
#: in order to decide whether to comment on reading it. Drawn from a measurement
#: of what actually gets read whole (2026-09-11, 1,382 reads over two weeks)
#: plus their obvious neighbours.
NUDGE_EXTENSIONS = frozenset({
    ".py", ".pyi", ".pyw",
    ".rs", ".go", ".rb", ".php", ".lua", ".swift", ".kt", ".java", ".cs",
    ".c", ".h", ".cpp", ".hpp", ".cc", ".hh",
    ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs",
    ".sh", ".ps1", ".bat", ".cmd", ".sql",
    ".md", ".rst", ".txt",
    ".json", ".jsonl", ".toml", ".yaml", ".yml", ".ini", ".cfg", ".properties",
    ".xml", ".html", ".css", ".scss", ".csv",
})

#: Excluded on purpose, each with its reason, so nobody later adds one back
#: because "it is text really":
#:   .ipynb -- Read renders notebooks as cells WITH OUTPUTS and tokensave_read
#:             does not, so a nudge here advertises a substitution that is not
#:             one.
#:   images and .pdf -- Read returns these as images/documents. Measured: 543 of
#:             1,382 whole-file reads, and the largest by payload (one .png
#:             serialised to 682 KB), so letting them reach the size gate would
#:             make base64 the loudest signal in the feature.
EXCLUDED_SPECIAL = frozenset({
    ".ipynb",
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".bmp", ".svg", ".pdf",
})


def response_bytes(tool_response):
    """Serialised UTF-8 bytes of what the hook was handed.

    NOT the file's size on disk: line numbering and truncation make those
    different numbers, and `tool_response` arrives as a dict (measured live on
    2026-09-11, not assumed). This is the payload, which is the thing that was
    expensive.
    """
    if tool_response is None:
        return 0
    try:
        text = (tool_response if isinstance(tool_response, str)
                else json.dumps(tool_response))
    except (TypeError, ValueError):
        return 0
    return len(text.encode("utf-8", "replace"))


def classify_read(tool_name, tool_input, size_bytes, in_metadata_project):
    """Pure. The whole eligibility decision, with no filesystem and no state.

    Shared verbatim with the adherence measurement -- see the module docstring
    of helpers/read_nudge.py for why that matters.
    """
    if tool_name != "Read":
        return NOT_READ
    tool_input = tool_input or {}
    # `file_path` in 320 of 320 real Read records. `path` is read too because a
    # documentation summary claimed that name, and being wrong here would mean a
    # hook that resolves nothing and silently never fires.
    path = tool_input.get("file_path") or tool_input.get("path") or ""
    if not path:
        return NO_PATH
    if "offset" in tool_input or "limit" in tool_input:
        return SLICED
    ext = os.path.splitext(path)[1].lower()
    if ext in EXCLUDED_SPECIAL or ext not in NUDGE_EXTENSIONS:
        return EXCLUDED_EXTENSION
    if size_bytes < MIN_RESPONSE_BYTES:
        return SMALL
    if not in_metadata_project:
        return NO_METADATA_PROJECT
    return ELIGIBLE


def project_with_tokensave_metadata(file_path, cwd, max_ancestors=MAX_ANCESTORS):
    """Does a `.tokensave/` sit at or above this file, within this session?

    Bounded at `cwd`, because an unbounded walk lets one stray
    `D:/projects/.tokensave` mark every unrelated child project as served. A
    file outside `cwd` entirely is not this session's project, so it stops at
    the ancestor bound rather than climbing to the drive root.

    Lexical throughout -- see rule 3 in helpers/read_nudge.py.
    """
    try:
        current = os.path.dirname(os.path.normcase(os.path.abspath(file_path)))
    except (OSError, ValueError):
        return False

    stop = ""
    if cwd:
        try:
            stop = os.path.normcase(os.path.abspath(cwd))
        except (OSError, ValueError):
            stop = ""
        # A file outside the session's directory is not this session's project.
        # Tools can be handed an absolute path anywhere on the machine, and
        # walking up from one would let an unrelated repository's metadata
        # answer for it.
        if stop and current != stop and not current.startswith(stop + os.sep):
            return False

    for _ in range(max_ancestors):
        try:
            if os.path.isdir(os.path.join(current, ".tokensave")):
                return True
        except OSError:
            return False
        # `cwd` itself is tested, and nothing above it is: one stray
        # `D:/projects/.tokensave` must not mark every repository beneath it.
        if stop and current == stop:
            return False
        parent = os.path.dirname(current)
        if parent == current:
            return False
        current = parent
    return False


def _temp_root():
    """The seam the tests patch, and the lazy import in one place."""
    import tempfile

    return tempfile.gettempdir()


def _digest(text):
    import hashlib

    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _state_dir(session_id):
    return os.path.join(_temp_root(), STATE_ROOT,
                        _digest(session_id or "no-session")[:16])


def claim_first_sighting(session_id, file_path):
    """True exactly once per (session, file). Atomic, no read-modify-write.

    `O_CREAT | O_EXCL` IS the test and the claim in one syscall, so two hooks
    racing on the same file cannot both see "not yet nudged" -- which a shared
    JSON state file could not prevent, and which parallel PostToolUse execution
    makes possible even though it measured 0 of 320 reads on this machine.

    Bounded: once the directory reaches MAX_MARKERS a sentinel is dropped, and
    from then on the hot path is a single `exists` rather than a directory walk.
    Markers are empty files, so bounding the count bounds the bytes.

    It stores no paths, because it does not need them -- that is a "keep no more
    than the job requires" rule, not a claim of anonymisation.
    """
    directory = _state_dir(session_id)
    sentinel = os.path.join(directory, CAPPED_SENTINEL)
    try:
        if os.path.exists(sentinel):
            return False
        os.makedirs(directory, exist_ok=True)
        digest = _digest(os.path.normcase(os.path.abspath(file_path)))
        try:
            handle = os.open(os.path.join(directory, digest[:32]),
                             os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        except FileExistsError:
            return False
        os.close(handle)
        count = 0
        with os.scandir(directory) as entries:
            for _entry in entries:
                count += 1
                if count > MAX_MARKERS:
                    break
        if count > MAX_MARKERS:
            os.close(os.open(sentinel, os.O_CREAT | os.O_WRONLY))
        return True
    except OSError:
        return False


def decide(payload):
    """`(verdict, advice_or_empty)`. No permission key is produced anywhere."""
    if os.environ.get(ENV_DISABLE):
        return DISABLED, ""
    tool_input = payload.get("tool_input") or {}
    path = tool_input.get("file_path") or tool_input.get("path") or ""
    verdict = classify_read(
        payload.get("tool_name"),
        tool_input,
        response_bytes(payload.get("tool_response")),
        project_with_tokensave_metadata(path, payload.get("cwd") or ""),
    )
    if verdict != ELIGIBLE:
        return verdict, ""
    if not claim_first_sighting(payload.get("session_id") or "", path):
        return ALREADY_NUDGED, ""
    return ELIGIBLE, ADVICE


def main():
    """Fail open, always. A broken advisory must never cost anybody a read."""
    try:
        payload = json.loads(sys.stdin.read() or "{}")
        if not isinstance(payload, dict):
            return
        _verdict, advice = decide(payload)
        if not advice:
            return
        sys.stdout.write(json.dumps({"hookSpecificOutput": {
            "hookEventName": "PostToolUse",
            "additionalContext": advice,
        }}))
    except Exception:
        return


if __name__ == "__main__":
    main()
