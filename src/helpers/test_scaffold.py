"""test_scaffold — Generate starter pytest files from per-style templates (v4.13).

Powers Test Manager Tab 4. Pick a ``src/`` file + a template kind, get
a ``tests/test_<basename>.py`` with the right fixture imports + a
couple of placeholder test functions for the user to fill in.

Templates (modelled on the v4.12 test files):

* ``pure_helper``       — single-purpose helpers with no I/O. Template
                          mirrors ``tests/test_doc_grounding.py``: plain
                          ``def test_*`` functions, no fixtures.
* ``subprocess_helper`` — subprocess-bound helpers (git/npm/codegraph).
                          Template mirrors ``tests/test_install_codegraph.py``:
                          ``mocker.patch("module.subprocess.run", ...)`` with
                          argv assertions.
* ``dialog_tk``         — ``tk.Toplevel`` dialogs. Template mirrors
                          ``tests/test_dialog_checks.py``: ``@pytest.mark.tk``,
                          uses ``tk_root`` + ``mock_config`` + ``mocker``.
* ``blank``             — minimal pytest file with conftest imports + one
                          stub test. Use for anything that doesn't fit
                          the three patterns above.

All templates include TODO comments at the points where the user fills
in implementation. Generated files COMPILE and PASS pytest immediately
(stub tests are ``assert True``) so the user gets fast green feedback
before customising.

Pure module — no Tk, no subprocess, no global state.
"""
from __future__ import annotations

import os
from typing import Literal


TemplateKind = Literal["pure_helper", "subprocess_helper", "dialog_tk", "blank"]

TEMPLATES: tuple[TemplateKind, ...] = (
    "pure_helper", "subprocess_helper", "dialog_tk", "blank"
)


# ── Source-path → module-import string ───────────────────────────────────

def _source_to_module(source_path: str, project_root: str) -> tuple[str, str]:
    """Map ``src/helpers/foo.py`` → ``("helpers.foo", "foo")``.

    Returns ``(import_path, basename_without_ext)``. Used by every
    template to build the right ``from <import_path> import ...`` line.
    """
    src_root = os.path.join(project_root, "src")
    rel = os.path.relpath(source_path, src_root).replace("\\", "/")
    parts = rel[:-len(".py")].split("/")
    return ".".join(parts), parts[-1]


