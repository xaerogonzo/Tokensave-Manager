# ── Test-file path resolution ────────────────────────────────────────────

def _test_filename_for(source_path: str, project_root: str) -> str:
    """Return the conventional ``tests/test_<basename>.py`` filename.

    Mirrors the convention observed in the v4.12 test suite:

      * ``src/helpers/quality_checks.py``  → ``test_quality_checks.py``
      * ``src/dialogs/checks_dialog.py``   → ``test_dialog_checks.py``
      * ``src/dialogs/tool_manager.py``    → ``test_dialog_tool_manager.py``
      * ``src/controllers/help_tab.py``    → ``test_help_tab.py``

    Dialogs get the ``dialog_`` prefix and lose any trailing ``_dialog``
    suffix; helpers and controllers use the plain ``test_<basename>``
    form. Generated files match what ``test_discovery.scan_coverage_gaps``
    will look for, so the source file flips from "✗ no tests" to
    "✓ tested" the moment the user clicks Generate.
    """
    src_root = os.path.join(project_root, "src")
    rel = os.path.relpath(source_path, src_root).replace("\\", "/")
    parts = rel[:-len(".py")].split("/")
    basename = parts[-1]
    if len(parts) >= 2:
        subpkg = parts[-2]
        if subpkg == "dialogs":
            basename_short = basename
            for suffix in ("_dialog",):
                if basename_short.endswith(suffix):
                    basename_short = basename_short[:-len(suffix)]
            return f"test_dialog_{basename_short}.py"
        # Controllers / helpers / etc. — plain form
        basename_short = basename
        for suffix in ("_ctrl",):
            if basename_short.endswith(suffix):
                basename_short = basename_short[:-len(suffix)]
        return f"test_{basename_short}.py"
    return f"test_{basename}.py"


# ── Public API ───────────────────────────────────────────────────────────

def preview_test_file(source_path: str, template: str,
                       project_root: str) -> str:
    """Return the rendered template content as a string.

    Pure — no filesystem write. Powers Tab 4's live preview pane.
    Raises ``ValueError`` for unknown ``template`` kinds.
    """
    if template not in _TEMPLATE_MAP:
        raise ValueError(
            f"unknown template {template!r}; expected one of {TEMPLATES}"
        )
    import_path, _basename = _source_to_module(source_path, project_root)
    test_filename = _test_filename_for(source_path, project_root)
    return _TEMPLATE_MAP[template].format(
        import_path=import_path,
        test_filename=test_filename,
    )


def generate_test_file(project_root: str, source_path: str,
                        template: str) -> tuple[bool, str]:
    """Render and write ``tests/test_<basename>.py`` from *template*.

    Refuses to overwrite an existing test file — the user must delete
    it via Tab 3 (Stale Tests) first. This is intentional: a half-
    written, customised test file should never be silently clobbered.

    Returns ``(ok, message_or_path)``.
    """
    if template not in _TEMPLATE_MAP:
        return False, (
            f"unknown template {template!r}; "
            f"expected one of {TEMPLATES}"
        )
    if not os.path.isfile(source_path):
        return False, f"source file not found: {source_path}"
    tests_dir = os.path.join(project_root, "tests")
    try:
        os.makedirs(tests_dir, exist_ok=True)
    except OSError as exc:
        return False, f"could not create tests/: {exc}"

    out_filename = _test_filename_for(source_path, project_root)
    out_path = os.path.join(tests_dir, out_filename)
    if os.path.exists(out_path):
        return False, (
            f"refusing to overwrite existing test file:\n  {out_path}\n\n"
            "Delete it via Test Manager → Stale Tests tab first."
        )

    content = preview_test_file(source_path, template, project_root)
    try:
        with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
    except OSError as exc:
        return False, f"could not write {out_path}: {exc}"

    return True, out_path
