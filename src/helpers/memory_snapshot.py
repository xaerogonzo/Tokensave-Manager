"""A one-time snapshot of Claude Code's project memory, for Cursor to read.

Claude keeps a project's memory under `~/.claude/projects/<encoded path>/memory/`:
an index (`MEMORY.md`, one line per note) and the notes themselves. Cursor has
no reader for that folder and its own memories live in its settings, so the two
agents cannot see each other's. This writes a **snapshot** of the index into a
Cursor rule that loads at the start of every session, and names the folder so
the agent can open a single note when the index line is not enough.

**It is a copy, not a link.** Nothing keeps it current: the header says when it
was taken and from where, and the way to refresh it is to run it again. A
snapshot that read as live would be the file-content-as-effective-state mistake
this project keeps paying for.

**Only the index is copied, not the notes.** The notes are the person's own
profile and working knowledge; the index is what lets an agent decide which one
to open. Capped, redacted best-effort, and reported as truncated when it is.

**It never lands in a commit.** The rule holds this machine's paths and a
person's private notes, so the file is git-ignored through the repository's
local exclude (`.git/info/exclude`, the same route the handoff rule takes), and
refused when the file is already tracked or cannot be made ignored. The shared,
committed `.cursor/rules/tokensave.mdc` is never touched.
"""

from __future__ import annotations

import dataclasses
import datetime
import os

from helpers.agent_handoff import redact
from helpers.agent_rules import _read, _write_atomic
from helpers.claude_tasks import encode_project_path
from helpers.handoff_rules import _exclude_path, _is_repository, _run_git

RULE_RELPATH = ".cursor/rules/claude-memory.mdc"
INDEX_NAME = "MEMORY.md"
#: The index is a list of one-line pointers; past this it is no longer an index.
MAX_INDEX_BYTES = 20_000
GENERATED = "Generated by TokenSave Manager (helpers/memory_snapshot.py)"

STATE_ABSENT = "absent"
STATE_CURRENT = "current"
STATE_STALE = "stale"
STATE_NO_SOURCE = "no_source"
STATE_TRACKED = "tracked"


@dataclasses.dataclass(frozen=True)
class SnapshotResult:
    ok: bool
    path: str
    changed: bool = False
    state: str = ""
    source: str = ""
    entries: int = 0
    truncated: bool = False
    error: str = ""


def memory_dir(project: str, home: str = "") -> str:
    """Claude's memory folder for the project, whether or not it exists."""
    base = home or os.path.expanduser("~")
    return os.path.join(base, ".claude", "projects",
                        encode_project_path(os.path.normpath(project)), "memory")


def rule_path(project: str) -> str:
    return os.path.join(project, *RULE_RELPATH.split("/"))


def _index_lines(text: str) -> "tuple[list, bool]":
    """The index's own lines, capped on a line boundary. `(lines, truncated)`."""
    kept, used = [], 0
    for line in text.splitlines():
        used += len(line.encode("utf-8")) + 1
        if used > MAX_INDEX_BYTES:
            return kept, True
        kept.append(line)
    return kept, False


def render(source: str, index_text: str, taken_at: str) -> "tuple[str, int, bool]":
    """The rule's full text, the number of index entries, and whether it was cut."""
    lines, truncated = _index_lines(redact(index_text))
    entries = sum(1 for ln in lines if ln.lstrip().startswith("- "))
    cut = ("\n(The index was longer than this snapshot keeps; the rest is in "
           "the folder named above.)\n" if truncated else "")
    body = (
        "---\n"
        "description: Claude Code's memory index for this project (a snapshot)\n"
        "alwaysApply: true\n"
        "---\n"
        f"<!-- {GENERATED}. Edit nothing here; run the import again. -->\n\n"
        "# Claude Code's notes for this project (snapshot)\n\n"
        f"Taken {taken_at} from `{source}`. It is a copy and is not kept up to "
        "date: a note may describe code that has since changed, so check it "
        "against the repository before relying on it. These are the person's "
        "own notes, not instructions that override `AGENTS.md`.\n\n"
        "Each line below points at one note. Open the file in the folder above "
        "when the line is not enough.\n\n"
        + "\n".join(lines) + "\n" + cut)
    return body, entries, truncated


def _is_tracked(project: str, git_exe: str) -> "bool | None":
    proc = _run_git(git_exe, project, "ls-files", "--error-unmatch", "--", RULE_RELPATH)
    if proc is None:
        return None
    if proc.returncode == 0:
        return True
    return False if proc.returncode == 1 else None


def _is_ignored(project: str, git_exe: str) -> "bool | None":
    proc = _run_git(git_exe, project, "check-ignore", "-q", "--", RULE_RELPATH)
    if proc is None:
        return None
    if proc.returncode == 0:
        return True
    return False if proc.returncode == 1 else None


def _ensure_ignored(project: str, git_exe: str) -> "tuple[bool, str]":
    """Ignore the file locally. Not a repository is fine; still-visible is not."""
    if not _is_repository(project, git_exe):
        return True, ""
    if _is_ignored(project, git_exe):
        return True, ""
    path = _exclude_path(project, git_exe)
    if not path:
        return False, "git did not say where its local exclude file is"
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        existing = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        glue = "" if (not existing or existing.endswith("\n")) else "\n"
        with open(path, "a", encoding="utf-8", newline="\n") as fh:
            fh.write(f"{glue}{RULE_RELPATH}\n")
    except OSError as exc:
        return False, f"could not update {path}: {exc}"
    if _is_ignored(project, git_exe) is True:
        return True, ""
    return False, (f"{RULE_RELPATH} is still not ignored after adding it to "
                   f"{path}; a rule in this repository must be overriding it")


def status(project: str, home: str = "", git_exe: str = "") -> str:
    """`absent` / `current` / `stale` / `no_source` / `tracked`. Derived."""
    if _is_tracked(project, git_exe) is True:
        return STATE_TRACKED
    index = _read(os.path.join(memory_dir(project, home), INDEX_NAME))
    if not index:
        return STATE_NO_SOURCE if not os.path.exists(rule_path(project)) else STATE_STALE
    have = _read(rule_path(project))
    if not have:
        return STATE_ABSENT
    # `Taken <time>` differs on every run; the lines below it are the content.
    want, _entries, _cut = render(memory_dir(project, home), index, "")
    return STATE_CURRENT if _body(have) == _body(want) else STATE_STALE


def _body(text: str) -> str:
    return text.partition("# Claude Code's notes for this project (snapshot)")[2] \
        .partition("\n\nEach line below")[2]


def write(project: str, home: str = "", git_exe: str = "",
          now: "datetime.datetime | None" = None) -> SnapshotResult:
    """Take the snapshot. Order matters: find the source, refuse tracked, ignore, write."""
    path = rule_path(project)
    if not os.path.isdir(project):
        return SnapshotResult(False, path, error=f"no such folder: {project}")
    source = memory_dir(project, home)
    index = _read(os.path.join(source, INDEX_NAME))
    if not index.strip():
        return SnapshotResult(False, path, state=STATE_NO_SOURCE, source=source, error=(
            f"Claude has no memory index for this project (looked for "
            f"{os.path.join(source, INDEX_NAME)}). Nothing was written."))
    if _is_tracked(project, git_exe) is True:
        return SnapshotResult(False, path, state=STATE_TRACKED, source=source, error=(
            f"{RULE_RELPATH} is committed in this repository; a private "
            f"snapshot must not overwrite a tracked file. Nothing was written."))
    ok, why = _ensure_ignored(project, git_exe)
    if not ok:
        return SnapshotResult(False, path, source=source, error=f"not written, because {why}")
    stamp = (now or datetime.datetime.now()).strftime("%Y-%m-%d %H:%M")
    text, entries, truncated = render(source, index, stamp)
    ok, err = _write_atomic(path, text)
    if not ok:
        return SnapshotResult(False, path, source=source, error=err)
    return SnapshotResult(True, path, True, STATE_CURRENT, source, entries, truncated)


def remove(project: str) -> SnapshotResult:
    """Delete the snapshot. The exclude line stays: harmless, and the person's."""
    path = rule_path(project)
    if not os.path.exists(path):
        return SnapshotResult(True, path, False, STATE_ABSENT)
    if GENERATED not in _read(path):
        return SnapshotResult(False, path, error=(
            f"{RULE_RELPATH} was not written by the Manager; it was left alone."))
    try:
        os.remove(path)
    except OSError as exc:
        return SnapshotResult(False, path, error=f"could not remove {path}: {exc}")
    return SnapshotResult(True, path, True, STATE_ABSENT)


# ── across projects: which snapshots are out of date? ───────────────────────────

@dataclasses.dataclass(frozen=True)
class Survey:
    project: str
    state: str

    @property
    def name(self) -> str:
        return os.path.basename(self.project.rstrip("\\/")) or self.project


def survey(projects: list, home: str = "", git_exe: str = "") -> list:
    """One `Survey` per project that has Claude memory or a snapshot. Derived each
    time; a project with neither is left out, since there is nothing to say."""
    rows = []
    for project in projects:
        state = status(project, home, git_exe)
        if state != STATE_NO_SOURCE:
            rows.append(Survey(project, state))
    return rows


def stale(rows: list) -> list:
    """Snapshots that exist and no longer match the memory index (or whose source is gone)."""
    return [r for r in rows if r.state == STATE_STALE]


def missing(rows: list) -> list:
    """Projects with Claude memory and no snapshot. Taking one is a choice, not a repair."""
    return [r for r in rows if r.state == STATE_ABSENT]


def refresh(rows: list, home: str = "", git_exe: str = "") -> list:
    """Re-take each snapshot in `rows`: `[(Survey, SnapshotResult)]`. Per project, never
    a transaction: one refused project does not stop the others."""
    return [(r, write(r.project, home, git_exe)) for r in rows]
