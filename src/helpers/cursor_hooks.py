"""The Cursor hook that records "a session ended" in the handoff ledger.

WHAT IT IS. One entry in Cursor's user-level `~/.cursor/hooks.json`, event
`sessionEnd`, that runs a small generated script. The script hands the Manager's
CLI the project folder, the session id, why it ended and where its transcript is
(`handoff --action marker`). It carries no prompt and no reply, only a path.

WHY `sessionEnd` AND NOTHING ELSE. Measured 2026-10-31 in a headless
`agent -p` run: only `sessionStart` and `sessionEnd` fired. `beforeSubmitPrompt`,
`afterAgentResponse` and `stop` did not, so a design leaning on them would have
recorded nothing for exactly the unattended runs. `sessionEnd` delivers
`workspace_roots` (plain Windows paths), `session_id`, `reason`, `final_status`
and `transcript_path`. It is fire-and-forget by Cursor's design, so it can never
loop an agent and cannot block one.

WHAT IT DOES NOT DO. It does not publish a handoff. A hook has no summary to
give, and inventing one from a transcript would file a guess as a note. A marker
says THAT a session happened; an agent that has something to say publishes.

AGENT-CONTROL CONFIG, so the discipline is the one for any such file: the edit
is computed as a PURE function of the existing text and shown as a diff before
anything is written; a file that does not parse is refused rather than replaced;
a timestamped backup is taken before any write; other hooks (the person's own
`sessionEnd` entries included) are preserved untouched; and the script is written
BEFORE the entry that names it, so there is never a hook pointing at nothing.

SCOPE OF WHAT IS PROVEN. A project-level `.cursor/hooks.json` was measured
working. A USER-level one, which this installs, is documented to run from
`~/.cursor/` (so the command is `./hooks/...`) but had not been exercised when
this was written; `docs/AGENT_BACKENDS.md` records the check that follows an
install.
"""

from __future__ import annotations

import dataclasses
import difflib
import json
import os
import shutil
import time

from helpers.agent_rules import _read, _write_atomic

HOOKS_FILE = "hooks.json"
SCRIPT_BASENAME = "tokensave_session_marker.py"
EVENT = "sessionEnd"
#: Seconds Cursor may let the hook run. It makes one local CLI call.
HOOK_TIMEOUT = 30

STATE_ABSENT = "absent"
STATE_CURRENT = "current"
STATE_STALE = "stale"
STATE_DUPLICATE = "duplicate"
STATE_UNREADABLE = "unreadable"


def cursor_home(home: str = "") -> str:
    """`~/.cursor`, resolved at call time (a test redirects the home folder)."""
    return os.path.join(home or os.path.expanduser("~"), ".cursor")


def hooks_json_path(home: str = "") -> str:
    return os.path.join(cursor_home(home), HOOKS_FILE)


def script_path(home: str = "") -> str:
    return os.path.join(cursor_home(home), "hooks", SCRIPT_BASENAME)


def hook_command() -> str:
    """User-level hooks run from `~/.cursor/`, so the path is relative to it
    (the docs: not `./hooks/x` from a project, but exactly that from here)."""
    return f"python ./hooks/{SCRIPT_BASENAME}"


def _is_ours(entry) -> bool:
    return isinstance(entry, dict) and SCRIPT_BASENAME in str(entry.get("command", ""))


def _our_entry() -> dict:
    return {"command": hook_command(), "timeout": HOOK_TIMEOUT}


# ── the generated script ────────────────────────────────────────────────────

_SCRIPT = '''"""Tell the TokenSave Manager that a Cursor session ended.

Generated by TokenSave Manager (helpers/cursor_hooks.py). Edit there, not here.
It reads Cursor's sessionEnd payload from stdin and passes a few fields to the
Manager's CLI. It prints nothing, never fails the session, and records only
paths and ids, never any prompt or reply text.
"""

import json
import subprocess
import sys

RUNNER = {runner}
CONFIG = {config}


def main():
    try:
        data = json.load(sys.stdin)
    except ValueError:
        return
    roots = data.get("workspace_roots") or []
    if not roots or not isinstance(roots[0], str):
        return
    argv = RUNNER + [
        "handoff", "--project", roots[0], "--config", CONFIG,
        "--action", "marker", "--agent", "cursor",
        "--session", str(data.get("session_id") or data.get("conversation_id") or ""),
        "--reason", str(data.get("reason") or ""),
        "--final-status", str(data.get("final_status") or ""),
        "--transcript", str(data.get("transcript_path") or ""),
        "--json",
    ]
    flags = 0x08000000 if sys.platform == "win32" else 0       # CREATE_NO_WINDOW
    subprocess.run(argv, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                   stderr=subprocess.DEVNULL, timeout=20, creationflags=flags)


try:
    main()
except Exception:
    pass
sys.exit(0)
'''


def render_script(runner_argv: list, config_path: str) -> str:
    """The hook script. Pure. Paths are JSON literals, so no quoting can break it."""
    return _SCRIPT.format(
        runner=json.dumps([p.replace("\\", "/") for p in runner_argv]),
        config=json.dumps(config_path.replace("\\", "/")))


# ── the edit, as a pure function ────────────────────────────────────────────

@dataclasses.dataclass(frozen=True)
class Plan:
    ok: bool
    new_text: str = ""
    changed: bool = False
    #: Why nothing can be done. Empty when `ok`.
    error: str = ""
    #: What was there: absent / current / stale / duplicate.
    before: str = STATE_ABSENT


def _parse(existing: "str | None"):
    """`(data, error)`. An absent or blank file is a fresh document."""
    if existing is None or not existing.strip():
        return {"version": 1, "hooks": {}}, ""
    try:
        data = json.loads(existing)
    except ValueError as exc:
        return None, f"hooks.json is not valid JSON ({exc}); it was not touched"
    if not isinstance(data, dict):
        return None, "hooks.json is not a JSON object; it was not touched"
    hooks = data.get("hooks", {})
    if not isinstance(hooks, dict):
        return None, "'hooks' in hooks.json is not an object; it was not touched"
    if not isinstance(hooks.get(EVENT, []), list):
        return None, f"'hooks.{EVENT}' in hooks.json is not a list; it was not touched"
    return data, ""


def status_of(existing: "str | None") -> str:
    data, error = _parse(existing)
    if data is None:
        return STATE_UNREADABLE
    entries = [e for e in (data.get("hooks") or {}).get(EVENT, []) if _is_ours(e)]
    if not entries:
        return STATE_ABSENT
    if len(entries) > 1:
        return STATE_DUPLICATE
    return STATE_CURRENT if entries[0] == _our_entry() else STATE_STALE


def plan_install(existing: "str | None") -> Plan:
    """What `hooks.json` should say after install. Never writes anything."""
    data, error = _parse(existing)
    if data is None:
        return Plan(False, error=error, before=STATE_UNREADABLE)
    before = status_of(existing)
    if before == STATE_CURRENT:
        return Plan(True, existing or "", False, before=before)
    hooks = dict(data.get("hooks") or {})
    kept = [e for e in hooks.get(EVENT, []) if not _is_ours(e)]
    hooks[EVENT] = kept + [_our_entry()]
    data = {"version": data.get("version", 1), **{k: v for k, v in data.items()
                                                  if k not in ("version", "hooks")},
            "hooks": hooks}
    text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    return Plan(True, text, text != (existing or ""), before=before)


def plan_uninstall(existing: "str | None") -> Plan:
    """The same file with only OUR entry removed."""
    data, error = _parse(existing)
    if data is None:
        return Plan(False, error=error, before=STATE_UNREADABLE)
    before = status_of(existing)
    if before == STATE_ABSENT:
        return Plan(True, existing or "", False, before=before)
    hooks = dict(data.get("hooks") or {})
    kept = [e for e in hooks.get(EVENT, []) if not _is_ours(e)]
    if kept:
        hooks[EVENT] = kept
    else:
        hooks.pop(EVENT, None)
    data = {**{k: v for k, v in data.items() if k != "hooks"}, "hooks": hooks}
    text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    return Plan(True, text, text != (existing or ""), before=before)


def unified_diff(old: "str | None", new: str, label: str) -> str:
    """The change as a person reads it. An absent file diffs against nothing."""
    return "".join(difflib.unified_diff(
        (old or "").splitlines(keepends=True), new.splitlines(keepends=True),
        fromfile=f"{label} (before)" if old else "(file does not exist)",
        tofile=f"{label} (after)"))


# ── doing it ────────────────────────────────────────────────────────────────

@dataclasses.dataclass(frozen=True)
class Outcome:
    ok: bool
    changed: bool = False
    backup: str = ""
    error: str = ""
    state: str = ""


def status(home: str = "") -> str:
    path = hooks_json_path(home)
    if not os.path.exists(path):
        return STATE_ABSENT
    return status_of(_read(path))


def _backup(path: str, now_ms: "int | None") -> "tuple[str, str]":
    """`(backup_path, error)`. Copied with metadata and verified byte-for-byte."""
    target = f"{path}.backup.{now_ms if now_ms is not None else int(time.time() * 1000)}"
    try:
        shutil.copy2(path, target)
        with open(path, "rb") as a, open(target, "rb") as b:
            if a.read() != b.read():
                return "", f"the backup {target} does not match the original"
    except OSError as exc:
        return "", f"could not back up {path}: {exc}"
    return target, ""


def install(runner_argv: list, config_path: str, home: str = "",
            now_ms: "int | None" = None) -> Outcome:
    """Write the script, back up `hooks.json`, then write the entry that names it."""
    path = hooks_json_path(home)
    existing = _read(path) if os.path.exists(path) else None
    plan = plan_install(existing)
    if not plan.ok:
        return Outcome(False, error=plan.error, state=plan.before)
    script_text = render_script(runner_argv, config_path)
    script = script_path(home)
    script_current = os.path.exists(script) and _read(script) == script_text
    if not plan.changed and script_current:
        return Outcome(True, False, state=STATE_CURRENT)
    ok, err = _write_atomic(script, script_text)          # first: nothing names it yet
    if not ok:
        return Outcome(False, error=err)
    backup = ""
    if plan.changed:
        if existing is not None:
            backup, err = _backup(path, now_ms)
            if err:
                return Outcome(False, error=err)
        ok, err = _write_atomic(path, plan.new_text)
        if not ok:
            return Outcome(False, backup=backup, error=err)
    return Outcome(True, True, backup, state=STATE_CURRENT)


def uninstall(home: str = "", now_ms: "int | None" = None) -> Outcome:
    """Remove our entry (keeping every other hook) and our generated script."""
    path = hooks_json_path(home)
    existing = _read(path) if os.path.exists(path) else None
    plan = plan_uninstall(existing)
    if not plan.ok:
        return Outcome(False, error=plan.error, state=plan.before)
    backup = ""
    if plan.changed:
        backup, err = _backup(path, now_ms)
        if err:
            return Outcome(False, error=err)
        ok, err = _write_atomic(path, plan.new_text)
        if not ok:
            return Outcome(False, backup=backup, error=err)
    script = script_path(home)
    if os.path.exists(script) and "Generated by TokenSave Manager" in _read(script):
        try:
            os.remove(script)
        except OSError as exc:
            return Outcome(False, backup=backup, error=f"could not remove {script}: {exc}")
    return Outcome(True, plan.changed, backup, state=STATE_ABSENT)
